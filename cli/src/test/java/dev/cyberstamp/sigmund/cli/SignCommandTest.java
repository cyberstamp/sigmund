package dev.cyberstamp.sigmund.cli;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.function.Supplier;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

/**
 * Signs with a {@code bc} tool holding a v4 and a v6 key, generated by {@code keygen} into stores
 * under the test's directory: a profile chooses which of the keys sign.
 */
class SignCommandTest {

    private static final Pattern FINGERPRINT = Pattern.compile("Fingerprint: ([0-9A-F]+)");

    @TempDir
    Path dir;

    @Test
    void aProfileSignsWithTheKeysOfItsTypesOnly() throws IOException {
        Path artifact = configureTwoKeys();

        Run run = run(SignCommand::new, "--file", artifact.toString(), "--profile", "classic");

        assertEquals(0, run.exitCode(), run.out() + run.err());
        assertEquals(1, blocks(artifact));
    }

    @Test
    void withoutAProfileEveryKeySigns() throws IOException {
        Path artifact = configureTwoKeys();

        Run run = run(SignCommand::new, "--file", artifact.toString());

        assertEquals(0, run.exitCode(), run.out() + run.err());
        assertEquals(2, blocks(artifact));
    }

    @Test
    void anUnknownProfileFailsNamingTheProfiles() throws IOException {
        Path artifact = configureTwoKeys();

        Run run = run(SignCommand::new, "--file", artifact.toString(), "--profile", "nosuch");

        assertEquals(1, run.exitCode());
        assertTrue(run.err().contains("Unknown signing profile: nosuch"), run.err());
    }

    /** Writes a config whose bc tool lists a v4 and a v6 key, and returns the artifact to sign. */
    private Path configureTwoKeys() throws IOException {
        writeConfig("");
        String v4 = generate("pgp4");
        String v6 = generate("pgp6");
        writeConfig("""
                    signing-fingerprint: [%s, %s]
                signing:
                  toolchain: [bc]
                  profiles:
                    classic: [pgp4]
                """.formatted(v4, v6));
        return Files.writeString(dir.resolve("lib-1.0.jar"), "artifact");
    }

    private void writeConfig(String rest) throws IOException {
        Path home = dir.resolve("bc");
        Files.writeString(dir.resolve("sigmund.yaml"), """
                tools:
                  bc:
                    gnupg-home: %s
                    cert-d-home: %s
                    bc-private-home: %s
                %s""".formatted(home.resolve("gnupg"), home.resolve("cert-d"), home.resolve("bc-private"), rest));
    }

    private String generate(String credentialType) {
        Run run = run(KeygenCommand::new, "--userid", "Alice <alice@example.com>", "--credential-type",
                credentialType);
        Matcher fingerprint = FINGERPRINT.matcher(run.out());
        assertTrue(fingerprint.find(), run.out() + run.err());
        return fingerprint.group(1);
    }

    private int blocks(Path artifact) throws IOException {
        String asc = Files.readString(dir.resolve(artifact.getFileName() + ".asc"));
        return asc.split("-----BEGIN PGP SIGNATURE-----", -1).length - 1;
    }

    private Run run(Supplier<Object> command, String... args) {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
        System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
        try {
            String[] all = new String[args.length + 2];
            all[0] = "--config";
            all[1] = dir.resolve("sigmund.yaml").toString();
            System.arraycopy(args, 0, all, 2, args.length);
            int exit = new CommandLine(command.get()).execute(all);
            return new Run(exit, out.toString(StandardCharsets.UTF_8), err.toString(StandardCharsets.UTF_8));
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
    }

    private record Run(int exitCode, String out, String err) {
    }
}
